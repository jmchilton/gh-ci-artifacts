import { mkdirSync, writeFileSync } from "fs";
import { dirname } from "path";

export type BlobTests = Record<string, Array<{ result: string; log?: string }>>;

/** Writes a minimal pytest-html (v4) report with an embedded data blob. */
export function writePytestHtml(path: string, tests: BlobTests): void {
  const blob = JSON.stringify({ environment: {}, tests })
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;");
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(
    path,
    `<html><head><title>report</title></head><body><p>Report generated by pytest-html</p><div id="data-container" data-jsonblob="${blob}"></div></body></html>`,
  );
}
